#!/usr/bin/env python
"""Shape validator for the three audit collections (contract §1).

Asserts required fields and types on every document in audit_transaction,
audit_error and audit_service. Designed to pass on BOTH the seeded sample rows
and on rows generated by novasim. Exits nonzero with a per-collection report on
any violation; otherwise prints PASS with counts.

Usage::

    . .venv/bin/activate
    python data/validate_shapes.py
"""
from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "agent"))
from nova_agent.config import settings  # noqa: E402
from nova_agent.db import get_db  # noqa: E402

DATE = dt.datetime


def is_str(v):
    return isinstance(v, str)


def is_int(v):
    return isinstance(v, int) and not isinstance(v, bool)


def is_date(v):
    return isinstance(v, dt.datetime)


def is_str_or_null(v):
    # authentic 'NULL' literals and real strings both allowed
    return isinstance(v, str)


# Each rule: (field, predicate, human description). Predicate receives the value;
# missing fields are reported separately (all listed fields are required).
TXN_RULES = [
    ("msg_id", is_int, "int"),
    ("trns_id", is_str, "str"),
    ("sessn_tkn_id", is_str, "str"),
    ("clnt_ip_addr", is_str, "str"),
    ("req_no", is_str, "str"),
    ("usr_rltnshp_no", is_str, "str"),
    ("trns_stts", lambda v: v in ("error", "success"), "one of {'error','success'}"),
    ("strt_time", is_date, "datetime"),
    ("end_time", is_date, "datetime"),
    ("usr_id", lambda v: is_str(v) and v.isdigit() and len(v) == 19, "19-digit str"),
    ("usr_typ", is_str, "str"),
    ("cmnd_id", is_str, "str"),
    ("chnl_id", lambda v: v in (2001, 1001), "one of {2001,1001}"),
    ("biz_req_input", is_str, "str (JSON)"),
    ("biz_resp_output", is_str, "str (JSON)"),
    ("crtd_by", is_str, "str"),
    ("crtd_on", is_date, "datetime"),
    ("trace_id", is_str_or_null, "str (may be 'NULL')"),
    ("nfrchk", is_str_or_null, "str (may be 'NULL')"),
    ("seq", is_int, "int"),
    ("channel", lambda v: v in ("mobile", "web"), "one of {'mobile','web'}"),
]

ERR_RULES = [
    ("msg_id", is_int, "int"),
    ("trns_id", is_str, "str"),
    ("sessn_tkn_id", is_str, "str"),
    ("err_cd", is_str, "str"),
    ("err_typ", lambda v: v in ("BUSINESS_EXCEPTION", "TECHNICAL_EXCEPTION"),
     "one of {'BUSINESS_EXCEPTION','TECHNICAL_EXCEPTION'}"),
    ("err_dscrptn", is_str, "str"),
    ("err_dtls", is_str, "str (JSON, may be 'NULL')"),
    ("crtd_by", is_str, "str"),
    ("crtd_on", is_date, "datetime"),
    ("err_time", is_date, "datetime"),
    ("usr_id", lambda v: is_str(v) and v.isdigit() and len(v) == 19, "19-digit str"),
    ("seq", is_int, "int"),
]
for _i in range(1, 6):
    ERR_RULES.append((f"biz_err_cd_{_i}", is_str_or_null, "str (may be 'NULL')"))
    ERR_RULES.append((f"biz_err_cd_{_i}_msg", is_str_or_null, "str (may be 'NULL')"))

SVC_RULES = [
    ("msg_id", is_int, "int"),
    ("trns_id", is_str, "str"),
    ("sessn_tkn_id", is_str, "str"),
    # trns_sts is authentically mixed-type across the fleet (§2.5): str 'success'/'0'/'-2'
    # AND numeric 0/-2 both appear in the sample; the agent normalizes on read.
    ("trns_sts", lambda v: v in ("success", "0", "-2", 0, -2), "one of {'success','0','-2',0,-2}"),
    # err_cd/err_msg absent (None) means the call carried no error — a valid successful service call.
    ("err_cd", lambda v: v is None or is_str(v) or is_int(v), "str | int | absent (may be '')"),
    ("err_msg", lambda v: v is None or is_str(v), "str | absent"),
    ("usr_id", lambda v: is_str(v) and v.isdigit() and len(v) == 19, "19-digit str"),
    ("srvc_rqst", is_str, "str (JSON)"),
    ("srvc_rspn", is_str, "str (JSON)"),
    ("srvc_id", is_str, "str"),
    ("systm_nm", is_str, "str (' UNIPAY' space preserved / 'EIS')"),
    ("api_url", is_str, "str"),
    ("rqst_id_sent", is_str, "str"),
    ("rqst_id_rcvd", is_str, "str"),
    ("crtd_by", is_str, "str"),
    ("crtd_on", is_date, "datetime"),
    ("strt_time", is_date, "datetime"),
    ("end_time", is_date, "datetime"),
    ("seq", is_int, "int"),
]

COLLECTIONS = [
    (settings.C_TXN, TXN_RULES),
    (settings.C_ERR, ERR_RULES),
    (settings.C_SVC, SVC_RULES),
]


def validate_collection(db, name, rules):
    violations = []
    count = 0
    for doc in db[name].find({}):
        count += 1
        ident = doc.get("_id")
        trns = doc.get("trns_id", "?")
        for field, pred, desc in rules:
            if field not in doc:
                violations.append(f"[{name}] _id={ident} trns_id={trns}: missing '{field}' (want {desc})")
                continue
            val = doc[field]
            try:
                ok = bool(pred(val))
            except Exception as exc:  # noqa: BLE001
                ok = False
                desc = f"{desc} (predicate error: {exc})"
            if not ok:
                shown = repr(val)
                if len(shown) > 60:
                    shown = shown[:57] + "..."
                violations.append(
                    f"[{name}] _id={ident} trns_id={trns}: field '{field}'={shown} "
                    f"is {type(val).__name__}, want {desc}"
                )
    return count, violations


def main() -> None:
    db = get_db()
    total_violations = 0
    counts = {}
    for name, rules in COLLECTIONS:
        count, violations = validate_collection(db, name, rules)
        counts[name] = count
        if violations:
            total_violations += len(violations)
            print(f"FAIL {name}: {len(violations)} violation(s) over {count} doc(s)")
            for v in violations[:50]:
                print("  " + v)
            if len(violations) > 50:
                print(f"  ... and {len(violations) - 50} more")
        else:
            print(f"OK   {name}: {count} doc(s) valid")

    if total_violations:
        print(f"\nRESULT: FAIL — {total_violations} violation(s)")
        sys.exit(1)
    print("\nPASS — all documents conform to contract §1")
    for name, count in counts.items():
        print(f"  {name}: {count}")


if __name__ == "__main__":
    main()
